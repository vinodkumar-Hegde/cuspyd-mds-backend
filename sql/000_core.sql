-- Complete standalone PostgreSQL schema; no external auth schema, RLS or triggers.
CREATE TABLE IF NOT EXISTS public.app_users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), email text UNIQUE,
    password_hash text, name text NOT NULL, mobile text, college text, state text,
    role text NOT NULL DEFAULT 'student' CHECK (role IN ('student','admin')),
    legacy_role text, is_active boolean NOT NULL DEFAULT true,
    password_reset_required boolean NOT NULL DEFAULT false,
    token_version integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid PRIMARY KEY REFERENCES public.app_users(id) ON DELETE CASCADE,
    name text, email text UNIQUE, mobile text, college text, state text,
    role text DEFAULT 'student', created_at timestamptz DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.questions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), subject_id text NOT NULL,
    year text NOT NULL, text text NOT NULL, options text[] NOT NULL,
    correct_option integer NOT NULL CHECK (correct_option BETWEEN 0 AND 3),
    explanation text NOT NULL DEFAULT '', topic text, image_url text,
    CHECK (cardinality(options) = 4)
);
CREATE TABLE IF NOT EXISTS public.tests (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), title text NOT NULL,
    type text NOT NULL CHECK (type IN ('ST','MT','GT','RANKER','MOCK')),
    status text DEFAULT 'DRAFT', questions jsonb NOT NULL,
    created_at timestamptz DEFAULT now(), answer_key jsonb, explanations jsonb,
    admin_message text
);
CREATE TABLE IF NOT EXISTS public.exam_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid REFERENCES public.app_users(id), test_id uuid REFERENCES public.tests(id),
    type text NOT NULL, start_time timestamptz DEFAULT now(), end_time timestamptz,
    answers jsonb, marked_for_review uuid[], is_completed boolean DEFAULT false
);
CREATE TABLE IF NOT EXISTS public.feature_settings (
    feature_key text PRIMARY KEY, is_visible boolean NOT NULL DEFAULT true
);
INSERT INTO public.feature_settings (feature_key) VALUES
    ('practice_exams'), ('test_history'), ('high_yield'), ('syndromes'), ('flow_charts')
    ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS public.high_yield_topics (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), subject_id text NOT NULL,
    year text NOT NULL, topic_name text NOT NULL, created_at timestamptz DEFAULT now(),
    question_image_url text, answer_image_url text
);
CREATE TABLE IF NOT EXISTS public.subject_backgrounds (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name text NOT NULL UNIQUE, image_url text NOT NULL, created_at timestamptz DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.syndromes (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), name text NOT NULL,
    description text, image_url text NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
